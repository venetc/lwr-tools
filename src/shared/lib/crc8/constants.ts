/** Generator polynomial of the CRC-8 checksum: 0x07 = 7, that is x⁸ + x² + x + 1. */
export const CRC_POLYNOMIAL = 0x07;

/** Mask of the highest bit of a byte: 0x80 = 128. */
export const HIGH_BIT_MASK = 0x80;

/** Mask that keeps the lowest 8 bits of a number: 0xFF = 255. */
export const BYTE_MASK = 0xFF;
